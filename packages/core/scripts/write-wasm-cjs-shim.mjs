#!/usr/bin/env node
/**
 * RFC-031 — write the CJS bridge for the async WASM entry.
 *
 * `@totemsdk/core/wasm` is an ESM async entry (wasm-bindgen web target), so CJS
 * consumers cannot `require` it. This shim lets them:
 *
 *   const { init, sha3_256 } = require('@totemsdk/core/wasm');
 *   await init();               // dynamic-imports the ESM entry
 *   sha3_256(data);             // synchronous thereafter
 *
 * Generated into dist/cjs/wasm-async.js by the core build.
 */

import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'dist', 'cjs');
mkdirSync(outDir, { recursive: true });

// CJS-context type declarations (dist/cjs is `{type: commonjs}`) so CJS consumers
// do not hit TS1479 when importing the async entry.
const dtsSrc = join(root, 'dist', 'wasm-async.d.ts');
if (existsSync(dtsSrc)) copyFileSync(dtsSrc, join(outDir, 'wasm-async.d.ts'));

const shim = `'use strict';
// Generated by scripts/write-wasm-cjs-shim.mjs — CJS bridge to the ESM async entry.
let mod = null;
async function init(module_or_path) {
  if (!mod) mod = await import('../wasm-async.js');
  // Node/Bun CJS cannot fetch(file://); default to the local wasm bytes.
  if (module_or_path === undefined) {
    const { readFileSync } = require('node:fs');
    const { dirname, join } = require('node:path');
    const glue = require.resolve('@totemsdk/core-wasm/web');
    module_or_path = { module_or_path: readFileSync(join(dirname(glue), 'totemsdk_core_wasm_bg.wasm')) };
  }
  return mod.init(module_or_path);
}
function initSync(...args) {
  if (!mod) throw new Error('@totemsdk/core/wasm: await init() before initSync()');
  return mod.initSync(...args);
}
module.exports = new Proxy({ init, initSync, default: init }, {
  get(target, prop) {
    if (prop in target) return target[prop];
    if (typeof prop === 'symbol') return undefined;
    // Forward at call time so destructuring before init still works.
    return (...args) => {
      if (!mod) throw new Error('@totemsdk/core/wasm: await init() before calling ' + String(prop));
      return mod[prop](...args);
    };
  },
});
`;

writeFileSync(join(outDir, 'wasm-async.js'), shim);
console.log('wrote dist/cjs/wasm-async.js (CJS bridge)');
