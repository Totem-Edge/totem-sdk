#!/usr/bin/env node
/**
 * Generate the public RFC index from RFC front matter. The curated README table
 * can highlight selected RFCs, but the complete index is generated so a new RFC
 * cannot be forgotten.
 *
 * Usage:
 *   node scripts/report-rfc-index.mjs           # check docs/rfc/README.md
 *   node scripts/report-rfc-index.mjs --write   # regenerate it
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const RFC_DIR = join(ROOT, 'docs', 'rfc');
const TARGET = join(RFC_DIR, 'README.md');

// Only index tracked/staged RFCs. Concurrent untracked drafts must not appear in
// the committed index until their author adds them.
const tracked = execFileSync('git', ['ls-files', '--', 'docs/rfc/RFC-*.md'], {
  cwd: ROOT,
  encoding: 'utf8',
}).split('\n').filter(Boolean);

const entries = tracked
  .map((rel) => rel.slice('docs/rfc/'.length))
  .sort()
  .map((name) => {
    const text = readFileSync(join(RFC_DIR, name), 'utf8');
    const title = text.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? name;
    const status = text.match(/^(?:\*\*)?Status:(?:\*\*)?\s*(.+)$/m)?.[1]?.trim() ?? 'Unknown';
    return { name, title, status };
  });

const escape = (value) => String(value).replace(/\|/g, '\\|');
const lines = [
  '# RFC index',
  '',
  '> Generated by `node scripts/report-rfc-index.mjs --write`. Do not edit by hand.',
  '',
  '| RFC | Title | Status |',
  '|---|---|---|',
  ...entries.map((entry) => `| [${escape(entry.name)}](${encodeURI(entry.name)}) | ${escape(entry.title)} | ${escape(entry.status)} |`),
  '',
  `Total: **${entries.length}** RFC documents.`,
  '',
];

const rendered = lines.join('\n');
if (process.argv.includes('--write')) {
  writeFileSync(TARGET, rendered);
  console.log(`wrote ${TARGET}`);
} else if (!existsSync(TARGET)) {
  console.error(`✗ ${TARGET} is missing; run: node scripts/report-rfc-index.mjs --write`);
  process.exit(1);
} else if (readFileSync(TARGET, 'utf8') !== rendered) {
  console.error(`✗ ${TARGET} is stale; run: node scripts/report-rfc-index.mjs --write`);
  process.exit(1);
} else {
  console.log(`RFC index: ${entries.length} documents in sync`);
}
