#!/usr/bin/env node
/**
 * Custody golden-script fixtures (RFC-039 / docs/CUSTODY-POLICY.md §4).
 *
 * The static custody gate (validate-custody.mjs) is a grep-level *existence*
 * check. This pins the **exact** locking script each value-bearing package
 * builds, by executing the real builder from its dist. A change to a custody
 * script must be intentional and reviewed in the committed fixture.
 *
 * Usage:
 *   node scripts/custody-golden.mjs          # regenerate custody-golden.json
 *   node scripts/custody-golden.mjs --check  # fail if the fixture is stale
 *
 * Requires the packages to be built (dist/). Wire into CI after `npm run build`.
 */
import './lib/init-core-wasm.mjs';
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT = join(__dirname, 'custody-golden.json');
const CHECK = process.argv.includes('--check');

const A = '0x' + 'aa'.repeat(32);
const B = '0x' + 'bb'.repeat(32);
const party = (partyId, pk, amount) => ({
  partyId,
  publicKeyDigest: pk,
  addressIndex: 0,
  contributionAmount: amount,
  settlementAddress: pk,
});

async function build() {
  const dist = (pkg) => import(join(ROOT, 'packages', pkg, 'dist', 'index.js'));
  const [statechain, omnia, factory, vtxo] = await Promise.all([
    dist('statechain'),
    dist('omnia'),
    dist('omnia-factory'),
    dist('omnia-vtxo'),
  ]);
  return {
    '@totemsdk/statechain': statechain.buildStatechainScript(A),
    '@totemsdk/omnia': omnia.buildEltooScript([
      { partyId: 'a', publicKeyDigest: A, addressIndex: 0 },
      { partyId: 'b', publicKeyDigest: B, addressIndex: 1 },
    ]),
    '@totemsdk/omnia-factory': factory.buildFactoryScript([party('a', A, 1000n), party('b', B, 500n)]),
    '@totemsdk/omnia-vtxo': vtxo.buildPoolScript({ operatorPublicKeyDigest: A, holders: [B], exitBlock: 1000 }),
  };
}

const scripts = await build();

if (CHECK) {
  if (!existsSync(OUT)) {
    console.error('✗ custody-golden.json missing — run: node scripts/custody-golden.mjs');
    process.exit(1);
  }
  const committed = JSON.parse(readFileSync(OUT, 'utf8')).scripts ?? {};
  const bad = [];
  for (const [pkg, script] of Object.entries(scripts)) {
    if (committed[pkg] !== script) bad.push(pkg);
  }
  if (bad.length > 0) {
    console.error(`✗ custody golden script drift: ${bad.join(', ')}`);
    console.error('  If intentional, regenerate: node scripts/custody-golden.mjs');
    process.exit(1);
  }
  console.log(`Custody golden: ${Object.keys(scripts).length} scripts match the committed fixtures.`);
} else {
  writeFileSync(OUT, JSON.stringify({ note: 'Generated by scripts/custody-golden.mjs', scripts }, null, 2) + '\n');
  console.log(`Custody golden: wrote ${Object.keys(scripts).length} scripts to custody-golden.json`);
}
