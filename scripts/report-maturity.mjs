#!/usr/bin/env node
/**
 * Generate the public package maturity matrix from the machine-readable gates
 * config and package manifests. This is the single source of truth for the
 * README/docs maturity table; do not hand-edit docs/maturity.md.
 *
 * Usage:
 *   node scripts/report-maturity.mjs           # check docs/maturity.md
 *   node scripts/report-maturity.mjs --write   # regenerate it
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const CONFIG_PATH = join(ROOT, 'scripts', 'workspace-gates.config.json');
const TARGET = join(ROOT, 'docs', 'maturity.md');
const config = JSON.parse(readFileSync(CONFIG_PATH, 'utf8'));

const LEVEL_ORDER = ['v1', 'rc', 'beta', 'alpha', 'unclassified', 'excluded'];
const TIER_ORDER = [0, 1, 2, 'outside', 'excluded'];

function readManifest(dir) {
  const path = join(ROOT, dir, 'package.json');
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, 'utf8'));
}

function levelOf(meta) {
  if (meta.status !== 'publishable') return 'excluded';
  return meta.maturity ?? 'unclassified';
}

const lines = [];
lines.push('# Package maturity');
lines.push('');
lines.push('> Generated by `node scripts/report-maturity.mjs --write`. Do not edit this file by hand.');
lines.push('>');
lines.push('> The level and support tier come from `scripts/workspace-gates.config.json`. See');
lines.push('> [RFC-063](rfc/RFC-063-PRODUCTION-READINESS-AND-MATURITY-PROMOTION.md) for what each');
lines.push('> level and tier mean, and the gates a package must pass before it is promoted.');
lines.push('>');
lines.push('> Tier 0 is the first-line production core, Tier 1 is the production-candidate');
lines.push('> set, Tier 2 is the required support-dependency set, and `outside` is not');
lines.push('> part of the first-line production promise.');
lines.push('>');
lines.push('> Tier 1 evidence plan: [TIER1-EVIDENCE-PLAN.md](TIER1-EVIDENCE-PLAN.md).');
lines.push('');

const entries = Object.entries(config.packages).map(([dir, meta]) => {
  const manifest = readManifest(dir);
  return {
    dir,
    name: manifest?.name ?? dir,
    version: manifest?.version ?? '—',
    level: levelOf(meta),
    tier: meta.supportTier ?? (meta.status === 'publishable' ? 'outside' : 'excluded'),
    status: meta.status,
    reason: meta.reason ?? meta.custody?.reason ?? '',
  };
});

const tierRank = (tier) => TIER_ORDER.indexOf(tier);
entries.sort((a, b) => {
  const tier = tierRank(a.tier) - tierRank(b.tier);
  if (tier !== 0) return tier;
  const level = LEVEL_ORDER.indexOf(a.level) - LEVEL_ORDER.indexOf(b.level);
  return level !== 0 ? level : a.name.localeCompare(b.name);
});

const counts = new Map();
for (const entry of entries) counts.set(entry.level, (counts.get(entry.level) ?? 0) + 1);
const tierCounts = new Map();
for (const entry of entries) tierCounts.set(entry.tier, (tierCounts.get(entry.tier) ?? 0) + 1);
lines.push('## Summary');
lines.push('');
lines.push('| Level | Packages |');
lines.push('|---|---:|');
for (const level of LEVEL_ORDER) {
  if (counts.has(level)) lines.push(`| ${level} | ${counts.get(level)} |`);
}
lines.push('');
lines.push('| Support tier | Packages |');
lines.push('|---|---:|');
for (const tier of TIER_ORDER) {
  if (tierCounts.has(tier)) lines.push(`| ${tier === 'outside' ? 'Outside production surface' : tier === 'excluded' ? 'Excluded' : `Tier ${tier}`} | ${tierCounts.get(tier)} |`);
}
lines.push('');
const publishableCount = entries.filter((entry) => entry.status === 'publishable').length;
const excludedCount = entries.length - publishableCount;
lines.push(`Total: **${publishableCount}** publishable packages + **${excludedCount}** excluded entries = **${entries.length}** workspace entries.`);
lines.push('');
lines.push('## Matrix');
lines.push('');
lines.push('| Package | Version | Level | Support tier | Directory |');
lines.push('|---|---|---|---|---|');
for (const entry of entries) {
  const tierLabel = entry.tier === 'outside' ? 'outside' : entry.tier === 'excluded' ? 'excluded' : String(entry.tier);
  lines.push(`| \`${entry.name}\` | ${entry.version} | ${entry.level} | ${tierLabel} | \`${entry.dir}\` |`);
}
lines.push('');

const rendered = lines.join('\n');
const mode = process.argv.includes('--write') ? 'write' : 'check';

if (mode === 'write') {
  writeFileSync(TARGET, rendered);
  console.log(`wrote ${TARGET}`);
} else if (!existsSync(TARGET)) {
  console.error(`✗ ${TARGET} is missing; run: node scripts/report-maturity.mjs --write`);
  process.exit(1);
} else {
  const current = readFileSync(TARGET, 'utf8');
  if (current !== rendered) {
    console.error(`✗ ${TARGET} is stale; run: node scripts/report-maturity.mjs --write`);
    process.exit(1);
  }
  console.log(`maturity matrix: ${entries.length} entries in sync`);
}
